"""Price list (xlsx) -> supabase/seed/cennik.sql, an upsert of every unit into public.units.

    python scripts\\import_cennik.py "G:\\My Drive\\...\\Zieger cennik final 082026  LV.xlsx"

Then run supabase/seed/cennik.sql in the Supabase SQL editor (after the migrations in supabase/migrations/).
Rerun whenever the price list changes: prices, areas and labels are overwritten, but a unit's status (set in /admin)
and its web settings (is_public, walkthrough_url ...) are kept. Expected columns, as in "Zieger cennik final 082026":
Číslo bytu | Izbovosť | Typ | Výhľad | Podlažie | Interiér | Exterier | Spolu | Orientácia | Cena s DPH | výmera s pódiom
Standard library only (no openpyxl on this notebook). price_per_m2 is generated in the database (price / total_area).
"""
import os, sys, zipfile, datetime
import xml.etree.ElementTree as ET

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
ORIENT = {"N": "S", "NE": "SV", "E": "V", "SE": "JV", "S": "J", "SW": "JZ", "W": "Z", "NW": "SZ"}   # -> Slovak
WALKS = {"a32": "/walk/a32/index.html", "a25": "/walk/a25/index.html", "byt01": "/walk/byt01/index.html"}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "supabase", "seed", "cennik.sql")


def read_sheet(path):
    """rows of the first sheet as lists of cell values (str / float), in column order A, B, C ..."""
    z = zipfile.ZipFile(path)
    ss = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
            ss.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
    rows = []
    for row in ET.fromstring(z.read("xl/worksheets/sheet1.xml")).iter("{%s}row" % NS["m"]):
        vals = {}
        for c in row.findall("m:c", NS):
            ref = c.get("r"); col = "".join(ch for ch in ref if ch.isalpha())
            v = c.find("m:v", NS)
            if v is None: continue
            x = ss[int(v.text)] if c.get("t") == "s" else v.text
            if c.get("t") not in ("s", "str", "inlineStr"):
                try: x = float(x)
                except ValueError: pass
            vals[col] = x
        if vals:
            n = max(ord(k) - 64 for k in vals if len(k) == 1)
            rows.append([vals.get(chr(65 + i)) for i in range(n)])
    return rows


def q(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(round(v, 2)) if isinstance(v, float) else str(v)
    return "'" + str(v).replace("'", "''") + "'"


def main(path):
    rows = read_sheet(path)
    head = [str(h or "").strip().lower() for h in rows[0]]
    want = ["číslo bytu", "izbovosť", "typ", "výhľad", "podlažie", "interiér", "exterier", "spolu", "orientácia", "cena s dph"]
    assert head[:10] == want, "unexpected columns: %r" % head
    label = os.path.splitext(os.path.basename(path))[0].strip()
    units = []
    for i, r in enumerate(rows[1:]):
        r = r + [None] * (11 - len(r))
        code = str(r[0] or "").strip()
        if not code or code.lower().startswith("spolu"): continue
        rooms, typ, view, floor, inter, ext, total, orient, price, podium = r[1:11]
        is_byt = code.upper().startswith("B")
        num = code[1:]
        gallery = round(total - ext - inter, 2)            # 4.-5. NP lofts: the list's interior is the lower level only
        units.append(dict(
            id=code, name=("Byt " if is_byt else "Ateliér ") + num, unit_type="flat" if is_byt else "atelier",
            layout=str(typ).strip(), floor_number=int(floor), rooms_count=int(rooms), rooms="%d-izb." % int(rooms),
            view_type=str(view).strip(), interior_area=round(inter, 2), gallery_area=gallery if gallery > 0.01 else 0.0,
            exterior_area=round(ext, 2), exterior_type="balkón" if ext > 0 else None, total_area=round(total, 2),
            area_with_podium=round(podium, 2) if isinstance(podium, float) else None,
            orientation=ORIENT.get(str(orient).strip().upper(), str(orient).strip()), price=round(price),
            price_list=label, sort_order=i + 1, is_public=True,
            selector_id=("byt" if is_byt else "a") + num.zfill(2)))
    for u in units: u["walkthrough_url"] = WALKS.get(u["selector_id"])
    cols = list(units[0].keys())
    keep = {"walkthrough_url", "is_public"}                 # web settings: set on insert, kept on update
    upd = [c for c in cols if c not in ("id",) and c not in keep]
    lines = ["-- generated by scripts/import_cennik.py from %r, %s - do not edit, rerun the script"
             % (os.path.basename(path), datetime.date.today().isoformat()),
             "-- %d units, total %s EUR" % (len(units), "{:,}".format(sum(u["price"] for u in units)).replace(",", " ")),
             "insert into public.units (%s, status) values" % ", ".join(cols)]
    lines.append(",\n".join("  (%s, 'available')" % ", ".join(q(u[c]) for c in cols) for u in units))
    lines.append("on conflict (id) do update set\n  " + ",\n  ".join("%s = excluded.%s" % (c, c) for c in upd) +
                 ",\n  walkthrough_url = coalesce(public.units.walkthrough_url, excluded.walkthrough_url),\n  updated_at = now();")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("%d units -> %s (total %s EUR)" % (len(units), os.path.normpath(OUT), "{:,}".format(sum(u["price"] for u in units))))


if __name__ == "__main__":
    main(sys.argv[1])
